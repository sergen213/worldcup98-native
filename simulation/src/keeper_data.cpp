// 0x4BEC34: clear both keeper blocks 0x6734F0, resolve the keeper tables (0x4BECBC, 0x4BEFFC,
// 0x4BF0F0, 0x4BF1D0) and set the block defaults.
void PlayerAI_reset_4BEC34(World& w) {
    w.pl.keeper[0] = KeeperBlock{};
    w.pl.keeper[1] = KeeperBlock{};
    // 0x4BECBC: rows 0x58929C + i*0x40 up to 0x589B9C.
    for (std::uint32_t r = 0x58929c; r < 0x589b9c; r += 0x40) {
        const int a = resolve(w, r + 4), b = resolve(w, r + 8);
        for (std::uint32_t off : {0x18u, 0x1cu, 0x20u, 0x24u})
            if (r32(r + off) != -1) w32(r + off, resolve(w, r + off));
        std::int32_t e4 = 0, ec = 0, e8 = 0, e18 = 0;
        const std::int32_t e0 = contact(w, a, &e4, &ec);
        contact(w, b, &e8, &e18);
        const std::int32_t e1c = Anim_boneHeightAt(w, a, -0x62);
        // 0x4BED8B..0x4BEDBD: boneHeight(b), markFrame0/1(a, b) results are discarded.
        goalCell(w, a, b, 3, 5, r + 0x29, r + 0x2a);
        goalCell(w, a, b, 3, 3, r + 0x2b, r + 0x2c);
        std::int8_t x1, y1, z1, x2, y2, z2;
        untraced_Anim_poseExtent(w, a, 1, &x1, &y1, &z1);
        untraced_Anim_poseExtent(w, b, 1, &x2, &y2, &z2);
        // 0x4BEE26: Anim_clipFrames(a) when byte +0x28 is 0 or 2; the result is discarded.
        w32(r + 4, a);
        w32(r + 8, b);
        w16(r + 0xc, e0);
        w16(r + 0xe, e4);
        w16(r + 0x10, ec);
        w16(r + 0x12, e18);
        w16(r + 0x14, e1c);
        w8(r + 0x2d, x1);
        w8(r + 0x2e, z1);
        w8(r + 0x2f, x2);
        w8(r + 0x30, z2);
        w8(r + 0x31, y2);
    }
    // 0x4BEFFC: rows 0x589B9C + i*0x28 up to 0x589C14.
    for (std::uint32_t r = 0x589b9c; r < 0x589c14; r += 0x28) {
        const int a = resolve(w, r + 4);
        std::int32_t l4 = 0, l8 = 0;
        const std::int32_t l10 = contact(w, a, &l4, &l8);
        const std::int32_t lc = Anim_boneHeightAt(w, a, -0x62);
        std::int8_t x, y, z;
        untraced_Anim_poseExtent(w, a, 1, &x, &y, &z); // written straight into +0x14/+0x15/+0x16
        w8(r + 0x14, x);
        w8(r + 0x15, y);
        w8(r + 0x16, z);
        w32(r + 4, a);
        w16(r + 8, l10);
        w16(r + 0xa, l4);
        w16(r + 0xc, l8);
        w16(r + 0xe, lc);
    }
    // 0x4BF0F0: row 0x589C14 (0x18 bytes).
    {
        const std::uint32_t r = 0x589c14;
        const int a = resolve(w, r + 4);
        std::int32_t l8 = 0, lc = 0;
        const std::int32_t l0 = contact(w, a, &l8, &lc);
        const std::int32_t l10 = Anim_boneHeightAt(w, a, -0x62);
        std::int8_t x, y, z;
        untraced_Anim_poseExtent(w, a, 1, &x, &y, &z);
        w8(r + 0x10, x);
        w8(r + 0x11, y);
        w8(r + 0x12, z);
        w32(r + 4, a);
        w16(r + 8, l0);
        w16(r + 0xa, l8);
        w16(r + 0xc, lc);
        w16(r + 0xe, l10);
    }
    // 0x4BF1D0: row 0x589C2C (0x24 bytes).
    {
        const std::uint32_t r = 0x589c2c;
        const int a = resolve(w, r + 4), b = resolve(w, r + 8);
        std::int32_t l4 = 0, lc = 0, l8 = 0, l10 = 0;
        const std::int32_t l0 = contact(w, a, &l4, &lc);
        contact(w, b, &l8, &l10);
        w32(r + 4, a);
        w32(r + 8, b);
        w16(r + 0xc, l0);
        w16(r + 0xe, l4);
        w16(r + 0x10, lc);
        w16(r + 0x12, l10);
    }
    for (KeeperBlock& k : w.pl.keeper) {
        k.k128 = k.k12c = k.k124 = k.k130 = 1;
        k.k010 = -1;
        k.busy = 0;
    }
}

