struct Range {
    std::uint32_t base;
    const std::uint8_t* p;
    std::uint32_t size;
};
const Range kRanges[3] = {{0x5892a0, kTabA, sizeof kTabA}, {0x59f440, kTabB, sizeof kTabB}, {0x5a04cc, kAsin, sizeof kAsin}};

